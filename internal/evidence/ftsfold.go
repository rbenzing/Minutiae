// The diacritic rule of the full-text tokenizers (unicode61 with remove_diacritics 2 and trigram with
// remove_diacritics 1, which behave alike), as the index applies it to text that went through
// NormalizeText: a letter that NFKC composed (an accented Latin letter) is reduced to its ASCII base
// by FTS5's own table of precomposed letters, and a combining mark that did not compose is dropped
// when it is one of the marks of FTS5's diacritic mask. Both tables were measured against the real
// tokenizers; TestSnippetFoldsLikeTheIndex sweeps the combining marks and the letters of Unicode
// against them, so a SQLite that changes either table fails that test.

// ftsStrippedMarks are the combining marks the tokenizers drop (a subset of U+0300 to U+036F).
var ftsStrippedMarks = [...][2]rune{
	{0x300, 0x304},
	{0x306, 0x30C},
	{0x30F, 0x30F},
	{0x311, 0x311},
	{0x31B, 0x31B},
	{0x323, 0x328},
	{0x32D, 0x32E},
	{0x330, 0x331},
}

func ftsStrippedMark(r rune) bool {
	if r < 0x300 || r > 0x331 {
		return false
	}
	for _, rg := range ftsStrippedMarks {
		if r >= rg[0] && r <= rg[1] {
			return true
		}
	}
	return false
}

