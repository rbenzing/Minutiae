// FTSFoldDiacritics applies the diacritic rule of the full-text tokenizers to text that went
// through NormalizeText, so a letter compares equal to the one the index holds for it. It is for
// display-time comparison (snippets) and is the one place that rule is written down; it changes
// nothing that is indexed.
func FTSFoldDiacritics(s string) string {
	plain := true
	for i := 0; i < len(s); i++ {
		if s[i] >= utf8.RuneSelf {
			plain = false
			break
		}
	}
	if plain {
		return s
	}
	out := make([]rune, 0, len(s))
	for _, r := range s {
		if b, ok := ftsDiacriticBase[r]; ok {
			r = b
		} else if ftsStrippedMark(r) {
			continue
		}
		out = append(out, r)
	}
	return string(out)
}
