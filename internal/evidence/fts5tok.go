// Go replicas of the two FTS5 tokenizers of the full-text indexes, so that verify can digest the
// postings a record must have without asking SQLite to build a second index (5D Task 14g). They are
// pinned to the SQLite of modernc.org/sqlite v1.60.1 and must agree with it byte for byte: a replica that
// is wrong would let verify call a genuine index corrupt or, worse, call a corrupt one genuine.
//
// What the replicas copy, read from the transpiled source (lib/sqlite_windows.go unless another file is
// named; the other platform files hold the same functions at other lines; the C names are in brackets):
//
//   - The word index is 'unicode61 remove_diacritics 2' with the default categories "L* N* Co"
//     [_fts5UnicodeCreate, line 34983: eRemoveDiacritic = 2, zCat = "L* N* Co", no tokenchars or
//     separators]. A token character is one the category table calls a letter, a number or private
//     use [_fts5UnicodeIsAlnum, line 35071, which is the category flag xor _fts5UnicodeIsException, an
//     empty set here]. A run of token characters is one token. [_fts5UnicodeTokenize, line 35075]
//     skips separators until it finds a character for which _fts5UnicodeIsAlnum holds (or an ASCII
//     character the ASCII table marks), then folds every character of the run into one buffer. Inside
//     a run a character is also accepted when _sqlite3Fts5UnicodeIsdiacritic holds
//     (a combining mark of FTS5's diacritic table) but such a mark can never START a token: a mark after
//     a separator is skipped. The fold [_sqlite3Fts5UnicodeFold, line 81411, with eRemoveDiacritic 2]
//     lowercases, applies FTS5's own case table and then _fts5_remove_diacritic (line 36287), which maps
//     a precomposed letter to its base letter and maps the combining marks it removes to 0; a character
//     whose fold is 0 is left out of the token (it adds no byte and does not end the run). A token that
//     would be empty is not produced because no character that can start a run folds to 0: the probes of
//     TestFTS5TokenTablesAreCurrent found only marks that continue a token among the dropped characters
//     (a start that folded to 0 would make an empty token and count a position, as the C code does).
//   - U+FFFE and U+FFFF (and a surrogate or an overlong form, which valid UTF-8 never holds) are read as
//     U+FFFD by both tokenizers (the tests of "iCode & 0xFFFFFFFE == 0xFFFE" in _fts5UnicodeTokenize and
//     _fts5TriTokenize); the tables hold the answers SQLite gave when they were probed as themselves.
//   - The trigram index is 'trigram case_sensitive 0 remove_diacritics 1' [_fts5TriCreate, line 34578:
//     bFold = 1, iFoldParam = 2 for any remove_diacritics other than 0]. [_fts5TriTokenize, line 34645]
//     reads characters, folds each with the same _sqlite3Fts5UnicodeFold, SKIPS every character whose
//     fold is 0, and passes every window of three consecutive kept characters as one token (the fold is
//     applied once, to each character; a space is a character). Positions count trigrams. Fewer than
//     three kept characters give no token.
//   - Where the cut is made: _fts5StorageInsertCallback (lib/sqlite.go:23541) cuts a token of more than
//     FTS5_MAX_TOKEN_SIZE (32768, lib/sqlite.go:902) bytes at that many bytes, the way a raw byte cut
//     does, so it may split a UTF-8 sequence, and it counts one position for every call, so a cut token
//     is still one token. The callback also counts the tokens of each column (szCol), which is what
//     _fts5StorageInsertDocsize (lib/sqlite.go:23567) stores, per column, as an SQLite varint in the
//     _docsize row.
//
// Both replicas accept only NormalizeText output, which is valid UTF-8 without NUL: that is all the index
// sees (NewFTSDoc). For a byte sequence that is not valid UTF-8 they treat each bad byte as U+FFFD and
// never panic, but they promise nothing about agreement with SQLite there. U+0000 is a separator for the
// word tokenizer (the ASCII table) and a dropped character for the trigram tokenizer.
//
// The per-code-point facts are not copied from the C tables. They are measured from the pinned SQLite
// and committed in fts5tok_tables.go (generated by TestFTS5TokenTablesAreCurrent under
// MINUTIAE_REGEN_FTS5_TABLES=1, which probes every scalar value), as ftsfold.go did for the diacritic
// tables. A driver upgrade fails TestFTS5ReplicaPinMatchesDriver and TestFTS5TokenTablesAreCurrent until
// the tables are regenerated and reviewed.
const (
	fts5ReplicaModule   = "modernc.org/sqlite v1.60.1"
	fts5ReplicaSQLite   = "3.53.4"
	fts5ReplicaSourceID = "2026-07-24 19:02:57 bf7c7f30031888f4e796e429ab3978879485813aaca6f641c7b33e4e09459bcc"
	fts5MaxTokenSize    = 32768 // FTS5_MAX_TOKEN_SIZE, lib/sqlite.go
)

// Kinds of a code point for the word tokenizer. A code point that is not listed in fts5TokKind is a
// token character (ftsKindToken).
const (
	ftsKindToken uint8 = iota // starts or continues a token
	ftsKindSep                // ends a token
	ftsKindCont               // continues a token, never starts one (the combining marks FTS5 removes)
)

// ftsKindRange lists the code points lo..hi of one non-default kind.
type ftsKindRange struct {
	lo, hi rune
	kind   uint8
}

// Modes of an ftsFoldRange: the fold of a code point c in lo..hi is c+val (ftsFoldDelta) or val
// (ftsFoldConst; 0 means the character is dropped). A code point in no range folds to itself.
const (
	ftsFoldDelta uint8 = iota
	ftsFoldConst
)

// ftsFoldRange lists the fold of the code points lo..hi.
type ftsFoldRange struct {
	lo, hi rune
	mode   uint8
	val    int32
}

func (r ftsFoldRange) fold(c rune) rune {
	if r.mode == ftsFoldConst {
		return r.val
	}
	return c + r.val
}

// ftsTokTable is the dense form of the generated ranges for the basic multilingual plane; the other planes
// are looked up in the ranges.
type ftsTokTable struct {
	kind [0x10000]uint8
	fold [0x10000]rune
}

var (
	ftsTokOnce sync.Once
	ftsTokTab  ftsTokTable
)

func ftsTokTables() *ftsTokTable {
	ftsTokOnce.Do(func() {
		for c := range ftsTokTab.fold {
			ftsTokTab.fold[c] = rune(c)
		}
		for _, r := range fts5TokKind {
			for c := r.lo; c <= r.hi && c < 0x10000; c++ {
				ftsTokTab.kind[c] = r.kind
			}
		}
		for _, r := range fts5TokFold {
			for c := r.lo; c <= r.hi && c < 0x10000; c++ {
				ftsTokTab.fold[c] = r.fold(c)
			}
		}
		ftsTokTab.kind[0] = ftsKindSep // U+0000: the ASCII table of the word tokenizer
		ftsTokTab.fold[0] = 0          // and a dropped character for the trigram tokenizer
	})
	return &ftsTokTab
}

// get returns the kind and the fold of c.
func (t *ftsTokTable) get(c rune) (kind uint8, fold rune) {
	if c < 0x10000 {
		return t.kind[c], t.fold[c]
	}
	fold = c
	if i := sort.Search(len(fts5TokKind), func(i int) bool { return fts5TokKind[i].hi >= c }); i < len(fts5TokKind) && fts5TokKind[i].lo <= c {
		kind = fts5TokKind[i].kind
	}
	if i := sort.Search(len(fts5TokFold), func(i int) bool { return fts5TokFold[i].hi >= c }); i < len(fts5TokFold) && fts5TokFold[i].lo <= c {
		fold = fts5TokFold[i].fold(c)
	}
	return kind, fold
}

// ftsRuneAt decodes the code point at text[i:]. A byte that is not valid UTF-8 is U+FFFD (size 1), as in the
// C tokenizers. U+FFFE and U+FFFF need no special case here: the C tokenizers read them as U+FFFD, and the
// generated tables hold what SQLite answered when they were probed as themselves.
func ftsRuneAt(text string, i int) (c rune, size int) {
	if b := text[i]; b < utf8.RuneSelf {
		return rune(b), 1
	}
	return utf8.DecodeRuneInString(text[i:])
}

// appendFTSRune appends c in UTF-8 the way the C tokenizers write it (a plain bit split with no
// check, so unlike utf8.AppendRune it does not replace a surrogate).
func appendFTSRune(b []byte, c rune) []byte {
	switch {
	case c < 0x80:
		return append(b, byte(c))
	case c < 0x800:
		return append(b, 0xC0+byte(c>>6&0x1F), 0x80+byte(c&0x3F))
	case c < 0x10000:
		return append(b, 0xE0+byte(c>>12&0x0F), 0x80+byte(c>>6&0x3F), 0x80+byte(c&0x3F))
	}
	return append(b, 0xF0+byte(c>>18&0x07), 0x80+byte(c>>12&0x3F), 0x80+byte(c>>6&0x3F), 0x80+byte(c&0x3F))
}

// tokenizeUnicode61 calls emit for every token of text under 'unicode61 remove_diacritics 2' with the
// categories "L* N* Co", with its position in the column. term is only valid during the call (a buffer
// reused by the next token). A term longer than fts5MaxTokenSize is cut at that many bytes.
func tokenizeUnicode61(text string, emit func(term []byte, pos int)) {
	tab := ftsTokTables()
	var arr [64]byte
	buf := arr[:0]
	pos := 0
	for i := 0; i < len(text); {
		c, size := ftsRuneAt(text, i)
		if k, _ := tab.get(c); k != ftsKindToken {
			i += size // a separator, or a mark that cannot start a token
			continue
		}
		buf = buf[:0]
		for i < len(text) {
			c, size = ftsRuneAt(text, i)
			k, f := tab.get(c)
			if k == ftsKindSep {
				break
			}
			i += size
			if f != 0 {
				buf = appendFTSRune(buf, f)
			}
		}
		if len(buf) > fts5MaxTokenSize {
			buf = buf[:fts5MaxTokenSize]
		}
		emit(buf, pos)
		pos++
	}
}

// tokenizeTrigram calls emit for every window of three kept characters of text under 'trigram
// case_sensitive 0 remove_diacritics 1'. term is only valid during the call.
func tokenizeTrigram(text string, emit func(term []byte, pos int)) {
	tab := ftsTokTables()
	var ring [3]rune
	var arr [12]byte
	kept, pos := 0, 0
	for i := 0; i < len(text); {
		c, size := ftsRuneAt(text, i)
		i += size
		_, f := tab.get(c)
		if f == 0 {
			continue // dropped: removed as a diacritic, it is not a character of any trigram
		}
		if kept < 3 {
			ring[kept] = f
			kept++
			if kept < 3 {
				continue
			}
		} else {
			ring[0], ring[1], ring[2] = ring[1], ring[2], f
		}
		buf := appendFTSRune(arr[:0], ring[0])
		buf = appendFTSRune(buf, ring[1])
		buf = appendFTSRune(buf, ring[2])
		emit(buf, pos)
		pos++
	}
}

// ftsReplicaOverride is a test seam: when it is set and returns a tokenizer for a table, ftsTokenizer
// answers that one instead of the replica. It is nil in production.
var ftsReplicaOverride func(table string) func(string, func([]byte, int))

// ftsTokenizer returns the replica of the tokenizer of an FTS table (one of FTSTables), or nil for any
// other name.
func ftsTokenizer(table string) func(string, func([]byte, int)) {
	if ftsReplicaOverride != nil {
		if f := ftsReplicaOverride(table); f != nil {
			return f
		}
	}
	switch table {
	case FTSWordTable:
		return tokenizeUnicode61
	case FTSSubTable:
		return tokenizeTrigram
	}
	return nil
}

// errFTSReplica is the failure of the self-test when the tokenizer replicas do not agree with this SQLite.
var errFTSReplica = errors.New("tokenizer replica does not match this SQLite")

// ftsReference is what the self-test reads from a fresh SQLite for the comparisons that need a
// reference: the _config rows of each new table, read before any insert.
type ftsReference struct{ config map[string][]keyedRow }

// appendSQLiteVarint appends v as an SQLite varint (big endian, 1 to 9 bytes), the encoding of
// SQLiteVarint.
func appendSQLiteVarint(b []byte, v uint64) []byte {
	if v>>56 != 0 {
		var t [9]byte
		t[8] = byte(v)
		v >>= 8
		for i := 7; i >= 0; i-- {
			t[i] = byte(v&0x7f) | 0x80
			v >>= 7
		}
		return append(b, t[:]...)
	}
	var t [9]byte
	n := 0
	for ; ; v >>= 7 {
		t[n] = byte(v & 0x7f)
		n++
		if v < 0x80 {
			break
		}
	}
	for i := n - 1; i >= 0; i-- {
		c := t[i]
		if i != 0 {
			c |= 0x80
		}
		b = append(b, c)
	}
	return b
}

// fts5PinError is nil when version and sourceID name the SQLite the tables were measured against, and
// otherwise an error wrapping errFTSReplica.
func fts5PinError(version, sourceID string) error {
	if version == fts5ReplicaSQLite && sourceID == fts5ReplicaSourceID {
		return nil
	}
	return fmt.Errorf("%w: this SQLite is %s (%s), the tables were measured against %s (%s)",
		errFTSReplica, version, sourceID, fts5ReplicaSQLite, fts5ReplicaSourceID)
}

// ftsSelfTest builds a fresh SQLite database in memory with both FTS tables, indexes ftsProbeCorpus into
// them and compares what SQLite holds (the postings of the fts5vocab 'instance' table and the _docsize
// blobs) with what the replicas produce. Any difference, and any other SQLite than the one the tables were
// measured against, wraps errFTSReplica. Any other error means the reference itself could not be built; the
// caller treats both as a failure of the check (a fail-closed problem, never a pass). It also returns the
// fresh _config rows of each table, read before the first insert.
func ftsSelfTest(ctx context.Context) (ftsReference, error) {
	db, err := sql.Open("sqlite", ":memory:")
	if err != nil {
		return ftsReference{}, fmt.Errorf("open the tokenizer reference database: %w", err)
	}
	defer func() { _ = db.Close() }()
	// One dedicated connection: a second connection to ":memory:" is a different, empty database.
	conn, err := db.Conn(ctx)
	if err != nil {
		return ftsReference{}, fmt.Errorf("open the tokenizer reference database: %w", err)
	}
	defer func() { _ = conn.Close() }()
	if _, err := conn.ExecContext(ctx, `PRAGMA temp_store = MEMORY`); err != nil {
		return ftsReference{}, fmt.Errorf("tokenizer reference database: %w", err)
	}
	var version, sourceID string
	if err := conn.QueryRowContext(ctx, `SELECT sqlite_version(), sqlite_source_id()`).Scan(&version, &sourceID); err != nil {
		return ftsReference{}, fmt.Errorf("tokenizer reference database: %w", err)
	}
	if err := fts5PinError(version, sourceID); err != nil {
		return ftsReference{}, err
	}
	ref := ftsReference{config: map[string][]keyedRow{}}
	for _, table := range FTSTables() {
		ddl, _ := FTSTableDDL(table)
		vocab, _ := FTSVocabDDL(table)
		for _, stmt := range []string{ddl, vocab} {
			if _, err := conn.ExecContext(ctx, stmt); err != nil {
				return ftsReference{}, fmt.Errorf("tokenizer reference database: create %s: %w", table, err)
			}
		}
		cfg, err := ftsReadConfig(ctx, conn, table)
		if err != nil {
			return ftsReference{}, err
		}
		ref.config[table] = cfg
	}
	for _, table := range FTSTables() {
		if err := ftsSelfTestTable(ctx, conn, table); err != nil {
			return ftsReference{}, err
		}
	}
	return ref, nil
}

// ftsReadConfig reads the _config rows of a table.
func ftsReadConfig(ctx context.Context, conn *sql.Conn, table string) ([]keyedRow, error) {
	rows, err := conn.QueryContext(ctx, `SELECT typeof(k), k, typeof(v), v FROM `+table+`_config ORDER BY k LIMIT `+strconv.Itoa(ftsMaxConfigRows+1)) //nolint:gosec // the table is one of the two FTS table constants
	if err != nil {
		return nil, fmt.Errorf("tokenizer reference database: read %s_config: %w", table, err)
	}
	defer func() { _ = rows.Close() }()
	out, err := scanKeyed(rows, ftsMaxConfigRows, func(e error) error { return e })
	if err != nil {
		return nil, fmt.Errorf("tokenizer reference database: read %s_config: %w", table, err)
	}
	return out, nil
}

// ftsPosting is one (document, column, position, term) entry of an index, in the order of the vocab
// table's rows when sorted by document, column name, then position.
type ftsPosting struct {
	doc  int64
	col  string
	off  int64
	term string
}

// ftsProbeDoc returns the two column texts of probe document i (rowid i+1): the strings rotate through
// the columns so each one is indexed as a summary and as a body.
func ftsProbeDoc(corpus []string, i int) (summary, body string) {
	return corpus[i], corpus[(i+1)%len(corpus)]
}

func ftsSelfTestTable(ctx context.Context, conn *sql.Conn, table string) error {
	tok := ftsTokenizer(table)
	if tok == nil {
		return fmt.Errorf("tokenizer reference database: no replica for %s", table)
	}
	corpus := ftsProbeCorpus()
	tx, err := conn.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("tokenizer reference database: %w", err)
	}
	defer func() { _ = tx.Rollback() }()
	st, err := tx.PrepareContext(ctx, `INSERT INTO `+table+` (rowid, summary, body) VALUES (?, ?, ?)`) //nolint:gosec // the table is one of the two FTS table constants
	if err != nil {
		return fmt.Errorf("tokenizer reference database: prepare insert into %s: %w", table, err)
	}
	for i := range corpus {
		s, b := ftsProbeDoc(corpus, i)
		if _, err := st.ExecContext(ctx, i+1, s, b); err != nil {
			_ = st.Close()
			return fmt.Errorf("tokenizer reference database: insert probe %d into %s: %w", i, table, err)
		}
	}
	if err := st.Close(); err != nil {
		return fmt.Errorf("tokenizer reference database: %w", err)
	}

	// What the replica says: the postings in (doc, column name, position) order, and the sizes.
	var want []ftsPosting
	sizes := make([][2]uint64, len(corpus))
	for i := range corpus {
		s, b := ftsProbeDoc(corpus, i)
		for _, c := range []struct {
			name, text string
			idx        int
		}{{"body", b, 1}, {"summary", s, 0}} { // the order of ORDER BY col: "body" < "summary"
			n := 0
			tok(c.text, func(term []byte, pos int) {
				want = append(want, ftsPosting{int64(i + 1), c.name, int64(pos), string(term)})
				n++
			})
			sizes[i][c.idx] = uint64(n)
		}
	}
	// The sizes first: a differing token count is the plainest symptom of a wrong replica.
	if err := ftsCompareDocsize(ctx, tx, table, sizes); err != nil {
		return err
	}
	return ftsComparePostings(ctx, tx, table, want)
}

// ftsCompareDocsize compares the _docsize rows of a probe database with the token counts of the replica.
func ftsCompareDocsize(ctx context.Context, tx *sql.Tx, table string, sizes [][2]uint64) error {
	rows, err := tx.QueryContext(ctx, `SELECT id, sz FROM `+table+`_docsize ORDER BY id`) //nolint:gosec // the table is one of the two FTS table constants
	if err != nil {
		return fmt.Errorf("tokenizer reference database: read %s_docsize: %w", table, err)
	}
	defer func() { _ = rows.Close() }()
	n := 0
	for rows.Next() {
		var id int64
		var sz []byte
		if err := rows.Scan(&id, &sz); err != nil {
			return fmt.Errorf("tokenizer reference database: read %s_docsize: %w", table, err)
		}
		if id != int64(n+1) || n >= len(sizes) {
			return fmt.Errorf("%w: %s_docsize holds a row for document %d where the replica expects %d", errFTSReplica, table, id, n+1)
		}
		exp := appendSQLiteVarint(appendSQLiteVarint(nil, sizes[n][0]), sizes[n][1])
		if string(sz) != string(exp) {
			return fmt.Errorf("%w: %s_docsize document %d holds x'%x' where the replica counts x'%x'", errFTSReplica, table, id, sz, exp)
		}
		n++
	}
	if err := rows.Err(); err != nil {
		return fmt.Errorf("tokenizer reference database: read %s_docsize: %w", table, err)
	}
	if n != len(sizes) {
		return fmt.Errorf("%w: %s_docsize holds %d rows, the replica expects %d", errFTSReplica, table, n, len(sizes))
	}
	return nil
}

// ftsComparePostings compares the fts5vocab 'instance' rows of a probe database with the replica's postings.
func ftsComparePostings(ctx context.Context, tx *sql.Tx, table string, want []ftsPosting) error {
	rows, err := tx.QueryContext(ctx, `SELECT doc, col, offset, term FROM `+ftsVocabName(table)+` ORDER BY doc, col, offset`) //nolint:gosec // the table is one of the two FTS table constants
	if err != nil {
		return fmt.Errorf("tokenizer reference database: read the vocab of %s: %w", table, err)
	}
	defer func() { _ = rows.Close() }()
	k := 0
	for rows.Next() {
		var got ftsPosting
		if err := rows.Scan(&got.doc, &got.col, &got.off, &got.term); err != nil {
			return fmt.Errorf("tokenizer reference database: read the vocab of %s: %w", table, err)
		}
		if k >= len(want) {
			return fmt.Errorf("%w: %s holds an entry the replica does not produce: %s", errFTSReplica, table, ftsPostingString(got))
		}
		if got != want[k] {
			return fmt.Errorf("%w: %s holds %s where the replica produces %s", errFTSReplica, table, ftsPostingString(got), ftsPostingString(want[k]))
		}
		k++
	}
	if err := rows.Err(); err != nil {
		return fmt.Errorf("tokenizer reference database: read the vocab of %s: %w", table, err)
	}
	if k != len(want) {
		return fmt.Errorf("%w: %s holds %d entries, the replica produces %d (first missing: %s)", errFTSReplica, table, k, len(want), ftsPostingString(want[k]))
	}
	return nil
}

func ftsPostingString(p ftsPosting) string {
	term := p.term
	if len(term) > 40 {
		term = term[:40] + "..."
	}
	return fmt.Sprintf("(document %d, column %s, position %d, term %q)", p.doc, p.col, p.off, term)
}
