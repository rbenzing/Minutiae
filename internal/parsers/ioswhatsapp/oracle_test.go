// attachmentRawKeys are the raw keys of how a message's file was looked up: the attachments of plan 4I2 task 5.
var attachmentRawKeys = []string{
	"media_state", "attachments_resolved", "attachments_unresolved", "attachments_ambiguous", "attachments_other_source",
	"attachments_lookup_undecided",
}

// withoutAttachments is the oracle with the attachment fields removed: the payload's attachments and the raw keys of the
// lookup (media_state and the attachment counters). Task 5 owns them and removes this filter (plan 4I2, Task 4 step 1).
func withoutAttachments(exp parsertest.Expect) parsertest.Expect {
	recs := make([]parsertest.ExpRecord, len(exp.Records))
	for i, r := range exp.Records {
		p := map[string]any{}
		for k, v := range r.Payload {
			if k != "attachments" {
				p[k] = v
			}
		}
		if raw, ok := p["raw"].(map[string]any); ok {
			cp := map[string]any{}
			for k, v := range raw {
				cp[k] = v
			}
			for _, k := range attachmentRawKeys {
				delete(cp, k)
			}
			p["raw"] = cp
		}
		r.Payload = p
		recs[i] = r
	}
	exp.Records = recs
	return exp
}

// The scenario oracle is generated by tools/fixtures/whatsapp_ios_chats.py, a second reading of the spec that shares no Go
// code with the parser (see its docstring: not independent of the design). Every record, warning and note it states must
// be what Parse produces, for every variant that has records; the variants the parser refuses state none (the probe tests
// cover them). The attachment fields are not compared until Task 5.
func TestIOSWhatsAppChatsMatchesOracle(t *testing.T) {
	compared := 0
	for _, v := range variants {
		fx := parsertest.LoadFixture(t, "testdata", v)
		if len(fx.Expect.Records) == 0 {
			continue
		}
		compared++
		t.Run(v, func(t *testing.T) {
			h := parsertest.NewHarness(t)
			b := bundleOf(h, fx, v)
			p := ioswhatsapp.Parser{}
			res := runLenient(t, h, p, b.Input(h, p, false), "wal-frames-not-applied", "whatsapp-ios-join-undecided")
			parsertest.AssertMatchesOracle(t, res, b, withoutAttachments(fx.Expect))
		})
	}
	if compared != 7 {
		t.Errorf("%d variants with records compared, want 7 (every variant but nomodel, othermodel and otherapp)", compared)
	}
}
