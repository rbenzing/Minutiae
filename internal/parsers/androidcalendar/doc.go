// Package androidcalendar parses the Android calendar provider database
// (com.android.providers.calendar, calendar.db, user versions 400 to 699): one
// calendar_event record per stored Events row, every time read exactly as the
// provider stores it (UTC milliseconds for a timed event, a date at a UTC midnight
// for an all-day event), nothing expanded (plan 4I3). The codes follow the AOSP
// CalendarContract; a soft-deleted event, an event of a deleted calendar and the
// provider's last-synced copy of an event are Deleted with their source, never
// live, and a flag that cannot be decided is stated, never guessed.
//
// The package holds the committed fixtures (testdata), generated by
// tools/fixtures/calendar_android.py from the DDL snapshots of
// tools/fixtures/schemas/calendar-android, which are cross-checked against the
// public AOSP calendar provider source (CROSSCHECK.md there), and their literal
// oracles.
package androidcalendar
